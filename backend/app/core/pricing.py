# 8. ТЕРМІН ДІЇ ПАКЕТА
# =============================================================================
# Без строку невикористані уроки живуть вічно й перетворюються на борг школи.
#
# Рахуємо в ДНЯХ ВІД ПЕРШОГО ЗАНЯТТЯ, а не в місяцях від оплати. Так робить
# Antischool, і це справді зручніше: немає суперечки «я ж оплатив у грудні,
# а почав у лютому». Дата першого уроку зафіксована в кабінеті й не обговорюється.
#
# Наша сітка щедріша за ринкову на кожній сходинці — це аргумент продажу,
# а не поступка. Порівняння з Antischool (їхні стандарт-пакети):
#   24 уроки: у них 180 днів, у нас 180
#   48 уроків: у них 240, у нас 300
#   96 уроків: у них 360, у нас 480
#   144 уроки: у них 360, у нас 600
#
# ⚠️ Поля в моделі Package поки немає. Щоб віддавати строк на фронт, потрібна
# колонка validity_days + міграція. Поки що це джерело правди для текстів
# оферти й сторінки цін.

VALIDITY_DAYS: Dict[int, int] = {
    6: 60, 8: 90, 12: 90, 16: 120, 20: 150, 24: 180, 32: 240, 36: 240,
    48: 300, 64: 360, 72: 390, 96: 480, 144: 600, 184: 720, 250: 900,
}


def validity_for(lessons: int) -> int:
    """Термін дії пакета в днях від першого заняття."""
    if lessons in VALIDITY_DAYS:
        return VALIDITY_DAYS[lessons]
    # Для нестандартної довжини: два уроки на тиждень плюс 50% запасу.
    return max(60, round(lessons / 2 * 1.5 * 7 / 10) * 10)


# Заморозка: термін дії продовжується на кількість днів заморозки.
FREEZE_DAYS_LARGE = 60      # пакети від 48 уроків
