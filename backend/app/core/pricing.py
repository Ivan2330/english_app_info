def course_rate(lessons: int, fmt: str) -> int:
    """Ставка за урок для тематичного курсу заданої довжини."""
    table = {
        "individual": COURSE_INDIVIDUAL,
        "pair": COURSE_PAIR,
        "group": COURSE_GROUP,
    }[fmt]
    # Найближча сходинка, не менша за задану довжину.
    for i, n in enumerate(COURSE_LADDER):
        if lessons <= n:
            return table[i]
    return table[-1]


