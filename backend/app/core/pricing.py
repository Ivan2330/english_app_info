# Нам це не підходить: ми український ФОП без іноземної прокладки, продаємо
# заняття з живим викладачем, і весь сайт побудований на обіцянках, які можна
# перевірити. «Повернень немає» суперечило б і закону, і власному тексту.
#
# Тому: невикористані уроки повертаються в будь-який момент дії пакета.
# Захист від зловживання — у ПЕРЕРАХУНКУ проведених уроків за ставкою
# найменшого пакета. Інакше можна купити 250 уроків заради ставки 340,
# відходити десять і забрати решту, фактично отримавши оптову ціну за роздріб.

REFUND_ADMIN_FEE = 300      # ₴, покриває комісію еквайрингу та роботу менеджера

# Перерахунок проведених уроків при поверненні — за ставкою найменшого пакета
# відповідної лінійки. Для дорослих індивідуально це 550 ₴ замість, скажімо,
# 390 ₴ у пакеті на 96 уроків.
REFUND_RATE_SOURCE = "перша сходинка лінійки"

REFUND_PROCESSING_DAYS = 10     # робочих днів на перерахування


def refund_amount(paid: int, lessons_used: int, base_rate: int,
                  school_at_fault: bool = False) -> int:
    """Скільки повернути за невикористані уроки.

    paid         — фактично сплачена сума за пакет
    lessons_used — скільки уроків проведено (включно зі згорілими за неявку)
    base_rate    — ставка НАЙМЕНШОГО пакета цієї лінійки (перерахункова)
    school_at_fault — якщо припинення з вини школи, адмінзбір не утримуємо

    Повертає 0, якщо проведене вже перекриває сплачене.
    """
    used_cost = lessons_used * base_rate
    fee = 0 if school_at_fault else REFUND_ADMIN_FEE
    return max(paid - used_cost - fee, 0)


