# сумах усе одно не пропустить, тому ПЧ вмикаємо вибірково.

CHAST_TIERS = [
    (10_000, 3),    # до 10 тис. — 3 частини
    (30_000, 6),    # 10–30 тис. — до 6
]
CHAST_MAX_TOTAL = 30_000   # вище — не показуємо взагалі


def chast_for(total_price: Optional[int]) -> tuple[bool, Optional[int]]:
    """Чи доступна ПЧ для цієї суми і на скільки частин."""
    if not total_price or total_price > CHAST_MAX_TOTAL:
        return False, None
    for limit, parts in CHAST_TIERS:
        if total_price <= limit:
            return True, parts
    return False, None


