"""Реальний IP відвідувача за зворотним проксі.

ЧОМУ ЦЕ ОКРЕМИЙ МОДУЛЬ
======================

`request.client.host` за nginx повертає IP **контейнера nginx**, однаковий
для всіх. Наслідки різні за тяжкістю:

* Лічильник візитів хешує `ip + user-agent + сіль + дата`. Якщо IP у всіх
  один, унікальних відвідувачів за день виходить рівно стільки, скільки
  різних user-agent, — тобто число, яке не означає нічого. Воронка на
  дашборді при цьому виглядає правдоподібно, і помилку помічають не одразу.
* У заявках і замовленнях збережений IP просто марний при розборі спірних
  ситуацій.

ЧОМУ ОСТАННІЙ ЕЛЕМЕНТ, А НЕ ПЕРШИЙ
==================================

`X-Forwarded-For` заповнює клієнт, і підробити його тривіально. Наш nginx
проставляє `$proxy_add_x_forwarded_for`, тобто **дописує** побачений ним
IP у кінець. Отже:

    X-Forwarded-For: <що прислав клієнт>, <справжній IP, доданий nginx>

Правий елемент додали ми — його й беремо. Брати лівий (як роблять у
більшості прикладів з інтернету) означає довіряти рядку, який відвідувач
склав сам: досить підставити чужий IP, щоб зіпсувати статистику або
сховатися в логах.

Якщо між нами й клієнтом з'явиться ще один проксі (Cloudflare тощо),
це місце треба переглянути: довірених хопів стане два.
"""

from __future__ import annotations

from fastapi import Request


def client_ip(request: Request) -> str | None:
    """IP відвідувача або None, якщо визначити не вдалося."""
    xff = request.headers.get("x-forwarded-for")
    if xff:
        # Останній непорожній елемент — той, який дописав наш nginx
        parts = [p.strip() for p in xff.split(",") if p.strip()]
        if parts:
            return parts[-1]

    # Прямий доступ (локальна розробка, запит повз проксі)
    return request.client.host if request.client else None
