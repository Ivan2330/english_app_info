"""Сертифікати: формат номера, нормалізація, контрольний символ.

ЩО БУЛО НЕ ТАК
==============

У моделі було два ідентифікатори — `serial_number` і `public_code` — і жоден
не був позначений як той, що вводить людина. На самому сертифікаті друкується
один номер; другий існував невідомо для чого й лише створював питання
«а який із них вводити».

Тепер: **номер один** — `serial_number`. `public_code` лишається в базі
заради вже виданих сертифікатів (перевірка приймає обидва), але нові
не отримують окремого коду.

ФОРМАТ НОМЕРА
=============

    PA-2026-7K3F9X

    PA     фіксований префікс школи
    2026   рік видачі — видно вік сертифіката без бази
    7K3F9X п'ять випадкових символів + контрольний

Алфавіт без `0`, `O`, `1`, `I`, `L` — ці символи плутають і на слух,
і при переписуванні з паперу.

**Контрольний символ** рахується з решти номера. Це дозволяє відсіяти
одруківку ще на фронті, до запиту на сервер: людина бачить «схоже на
помилку в коді» замість «сертифікат не знайдено», а це різні повідомлення
з дуже різним відчуттям.

НОРМАЛІЗАЦІЯ
============

Люди переписують номер із PDF як завгодно: малими літерами, з пробілами
замість дефісів, без дефісів узагалі. Порівнювати треба нормалізовані
значення з обох боків — інакше половина звернень буде «у мене не працює».
"""

from __future__ import annotations

import re
import secrets
from datetime import datetime

# Без 0/O, 1/I/L — найчастіші помилки при переписуванні з паперу
ALPHABET = "23456789ABCDEFGHJKMNPQRSTUVWXYZ"   # 31 символ
BASE = len(ALPHABET)

PREFIX = "PA"
RANDOM_LEN = 5          # + 1 контрольний = 6 символів у хвості


def _checksum(payload: str) -> str:
    """Контрольний символ за схемою зваженої суми за модулем 31.

    Ловить усі одиничні одруківки й більшість перестановок сусідніх символів —
    саме ті помилки, які роблять люди, переписуючи код з паперу.
    """
    total = 0
    for i, ch in enumerate(payload):
        if ch not in ALPHABET:
            continue
        total += (i + 1) * ALPHABET.index(ch)
    return ALPHABET[total % BASE]


def normalize(code: str) -> str:
    """Звести введене користувачем до канонічного вигляду.

    «pa 2026 7k3f9x», «PA20267K3F9X», «pa-2026-7k3f9x» → «PA-2026-7K3F9X»
    """
    if not code:
        return ""

    # Прибираємо все, крім літер і цифр: дефіси, пробіли, підкреслення.
    # Плутані символи (O/0, I/1/L) НЕ замінюємо: їх немає в алфавіті взагалі,
    # тож підставляти нема на що. Перша версія цієї функції намагалася їх
    # мапити й ламала рік — «2026» перетворювалося на «2O26».
    raw = re.sub(r"[^A-Za-z0-9]", "", code).upper()

    m = re.match(rf"^{PREFIX}(\d{{4}})([A-Z0-9]{{{RANDOM_LEN + 1}}})$", raw)
    if m:
        return f"{PREFIX}-{m.group(1)}-{m.group(2)}"

    # Старі сертифікати можуть мати інший формат — не ламаємо їх,
    # просто віддаємо у верхньому регістрі без розділових знаків.
    return raw


def is_well_formed(code: str) -> bool:
    """Чи схожий код на наш номер і чи сходиться контрольний символ.

    Викликається на фронті перед запитом. Повертає False і для чужого
    формату — тоді фронт усе одно робить запит (раптом це старий сертифікат),
    але може підказати, що номер виглядає дивно.
    """
    canonical = normalize(code)
    m = re.match(rf"^{PREFIX}-(\d{{4}})-([A-Z0-9]{{{RANDOM_LEN}}})([A-Z0-9])$", canonical)
    if not m:
        return False
    year, body, check = m.groups()
    return _checksum(f"{year}{body}") == check


def generate_serial(year: int | None = None) -> str:
    """Згенерувати новий номер сертифіката."""
    year = year or datetime.utcnow().year
    body = "".join(secrets.choice(ALPHABET) for _ in range(RANDOM_LEN))
    return f"{PREFIX}-{year}-{body}{_checksum(f'{year}{body}')}"


def verify_url(serial: str, site_url: str) -> str:
    """Посилання, яке зашивається в QR-код на сертифікаті.

    QR тут не прикраса: переписувати номер із PDF руками ніхто не хоче,
    і без нього більшість просто не перевірить сертифікат узагалі.
    """
    return f"{site_url.rstrip('/')}/verify-certificate?code={serial}"
